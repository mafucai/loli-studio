const { chromium } = require("playwright");
const { spawn } = require("child_process");
const fs = require("fs");
fs.mkdirSync("test-results", { recursive: true });
const server = spawn("python3", ["-m", "http.server", "8765", "--bind", "127.0.0.1"], { cwd: "prototype", stdio: "ignore" });
const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));
async function run() {
  await sleep(1000);
  const browser = await chromium.launch({ headless: true });
  const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
  const errors = [];
  page.on("pageerror", (error) => errors.push(String(error)));
  await page.goto("http://127.0.0.1:8765/index.html", { waitUntil: "domcontentloaded" });
  await page.fill("#in-prompt", "雾霾蓝英式下午茶");
  await page.click("[data-act='gen-words']");
  await page.click("[data-act='next'][data-step='img']");
  await page.click("[data-act='gen-img']");
  await page.click("[data-act='pass-img']");
  await page.click("[data-act='next'][data-step='part']");
  await page.click("[data-act='gen-bom']");
  await page.click("[data-act='next'][data-step='check']");
  await page.click("[data-act='run-check']");
  for (const name of ["小红书", "抖音", "淘宝", "拼多多", "闲鱼"]) await page.click(`text=${name} 官方搜索 >> xpath=.. >> text=原创`);
  await page.click("[data-act='mark-original']");
  await page.click("[data-act='next'][data-step='buy']");
  await page.click("[data-act='run-sourcing']");
  const prices = page.locator("[data-act='set-price']");
  for (let i = 0; i < await prices.count(); i++) { await prices.nth(i).fill("10"); await prices.nth(i).dispatchEvent("change"); }
  await page.click("[data-act='next'][data-step='look']");
  await page.click("[data-act='gen-combo']");
  await page.click("[data-act='next'][data-step='model']");
  await page.click("[data-act='gen-model']");
  await page.click("[data-act='next'][data-step='fact']");
  await page.click("[data-act='run-factories']");
  await page.fill("#factory-name", "真实工厂");
  await page.fill("#factory-region", "杭州");
  await page.fill("#factory-contact", "已核对");
  await page.fill("#factory-min", "30");
  await page.fill("#factory-cost", "160");
  await page.click("[data-act='add-factory']");
  await page.click("[data-act='pick-fact']");
  await page.click("[data-act='next'][data-step='cost']");
  await page.fill("#cost-price", "399");
  await page.fill("#cost-fee", "6");
  await page.fill("#cost-ship", "8");
  await page.fill("#cost-pack", "3");
  await page.fill("#cost-fixed", "500");
  await page.fill("#cost-qty", "100");
  await page.click("[data-act='run-finance']");
  if (!(await page.locator("text=总利润").count())) throw new Error("成本结果未显示");
  await page.click("#btn-history");
  if (!(await page.locator(".history-item").count())) throw new Error("历史未保存");
  await page.screenshot({ path: "test-results/flow.png", fullPage: true });
  if (errors.length) throw new Error(errors.join("\n"));
  await browser.close();
}
run().catch((error) => { console.error(error); process.exitCode = 1; }).finally(() => server.kill());
